-- ════════════════════════════════════════════════════════════
--  Relokates Removals — database schema (Neon Postgres)
--  Idempotent. Builds a fresh database or tops up an existing one.
--  Access is server-side only (DATABASE_URL), so Row Level Security is off.
-- ════════════════════════════════════════════════════════════

-- ── Leads (written by the public quote form and the admin "+ Add customer") ──
CREATE TABLE IF NOT EXISTS relokates_quote_request (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz DEFAULT now(),
  name       text,
  email      text,
  phone      text,
  service    text,
  move_from  text,
  move_to    text,
  move_date  text,
  property   text,
  message    text,
  source     text,
  status     text DEFAULT 'new',
  notes      jsonb DEFAULT '[]'::jsonb,   -- internal staff notes [{at,text}]
  updated_at timestamptz DEFAULT now(),
  value      numeric(10,2),
  costs      jsonb DEFAULT '[]'::jsonb    -- job cost lines [{label,amount}]
);
CREATE INDEX IF NOT EXISTS relokates_quote_request_status_idx
  ON relokates_quote_request (status);

-- ── Appointments / bookings ──
-- lead_id is intentionally not a foreign key; the app manages the relation.
CREATE TABLE IF NOT EXISTS relokates_appointments (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_id          bigint NOT NULL,
  type             text NOT NULL CHECK (type IN ('survey', 'move', 'packing')),
  scheduled_for    timestamptz NOT NULL,
  duration_minutes int NOT NULL DEFAULT 60,
  address          text,
  notes            text,
  gcal_event_id    text,
  email_sent       boolean DEFAULT false,
  created_at       timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS relokates_appointments_lead_idx
  ON relokates_appointments (lead_id);
CREATE INDEX IF NOT EXISTS relokates_appointments_when_idx
  ON relokates_appointments (scheduled_for);

-- ── Call reminders (daily cron /api/admin/reminders-run) ──
CREATE TABLE IF NOT EXISTS reminders (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_id       bigint NOT NULL,
  remind_on     date NOT NULL,        -- YYYY-MM-DD
  remind_time   text,                 -- HH:MM (local UK time)
  note          text,
  gcal_event_id text,                 -- the "Call ..." Google Calendar event
  sent          boolean DEFAULT false,
  sent_at       timestamptz,
  created_at    timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS reminders_lead_idx ON reminders (lead_id);
CREATE INDEX IF NOT EXISTS reminders_due_idx  ON reminders (remind_on, sent);

-- ── Team activity log ──
CREATE TABLE IF NOT EXISTS activity_log (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  at         timestamptz NOT NULL DEFAULT now(),
  actor      text NOT NULL DEFAULT 'unknown',
  action     text NOT NULL DEFAULT '',
  lead_id    text,
  lead_name  text DEFAULT '',
  detail     text DEFAULT ''
);
CREATE INDEX IF NOT EXISTS activity_log_at_idx ON activity_log (at DESC);
